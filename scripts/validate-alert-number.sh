#!/usr/bin/env bash
# =============================================================================
# alert_number 守卫脚本：判定输入是否为**正整数**
# =============================================================================
# 用途：在把 `alert_number` 用于任何**公开内容**（Issue 标题 / 去重指纹 / 正文）
#       或任何 API 路径之前，先验证它是正整数。
#
# 背景（威胁模型）：
#   `alert_number` 来自分流 artifact（本地落盘的 JSON），其内容可被上游异常或
#   提示词影响而漂移。若只做「非空」判定，任意文本（**含漏洞详情**）都会被拼进
#   公开 Issue 的标题与指纹，从而在协调披露期内泄露可利用细节。本脚本把校验
#   收敛到**唯一实现**，避免同一规则在多处手写正则而漂移。
#
# 契约：
#   用法：validate-alert-number.sh <value>
#   退出码：0 = 合法正整数；1 = 非法（调用方须跳过该条，**绝不**放行）
#   stdout：合法时回显规范化后的十进制整数（去除前导零，便于指纹/标题统一）
# =============================================================================
set -euo pipefail

value="${1-}"

# 严格全串匹配：只允许纯十进制数字，且**必须**为正整数（拒绝 0）。
# 说明：
#   · `[0-9]` 而非 `[[:digit:]]`：后者在部分 locale 下会匹配全角数字等非 ASCII 字符；
#   · 前后锚点 `^...$`：杜绝 `1abc` / `123\n` / `#12` / `</title>` 之类的夹带；
#   · 显式排除全 0：`0`、`00` 不是有效告警编号（CodeQL 编号自 1 起）。
if [[ ! "$value" =~ ^[0-9]+$ ]]; then
  printf '非数字，拒绝：%s\n' "$value" >&2
  exit 1
fi

# 去掉前导零后必须仍非空且不等于 0，才视为正整数
normalized="$(printf '%s' "$value" | sed -E 's/^0+//')"
if [[ -z "$normalized" ]]; then
  printf '非正整数（全零），拒绝：%s\n' "$value" >&2
  exit 1
fi

# 长度上限兜底：CodeQL 告警编号远小于 2^63，超过 18 位必属异常输入
if [[ "${#normalized}" -gt 18 ]]; then
  printf '数值越界，拒绝：%s\n' "$value" >&2
  exit 1
fi

printf '%s' "$normalized"
